#!/usr/bin/env python3
"""Embeds design/role-ghosts/<role>/{logo,line,working}.svg into Sources/SieveSciApp/RoleGhostSVG.swift.

The app target has no resource bundle (see BrandSVG.swift), so artwork ships as Swift string literals.
Missing files become empty strings; the app then falls back to SF Symbols.

    python3 scripts/embed-role-ghosts.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "design/role-ghosts")
OUT = os.path.join(ROOT, "Sources/SieveSciApp/RoleGhostSVG.swift")
ROLES = [("main", "research"), ("worker", "worker"), ("checker", "checker"), ("verifier", "verifier")]
KINDS = ["logo", "line", "working", "base", "prop"]


def load(folder, kind):
    p = os.path.join(SRC, folder, kind + ".svg")
    if not os.path.exists(p):
        return ""
    s = open(p, encoding="utf-8").read()
    s = re.sub(r"<\?xml[^>]*\?>", "", s)
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    return s.strip()


def main():
    lines = ["// Generated by scripts/embed-role-ghosts.py from design/role-ghosts/. Do not edit by hand.",
             "// swiftlint:disable all", "", "enum RoleGhostSVG {"]
    for role, folder in ROLES:
        for kind in KINDS:
            body = load(folder, kind)
            assert '"""#' not in body
            lines.append(f'    static let {role}_{kind} = #"""\n{body}\n"""#' if body else f'    static let {role}_{kind} = ""')
    lines.append("}")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    found = sum(1 for r, f in ROLES for k in KINDS if load(f, k))
    print(f"wrote {OUT} ({found}/{len(ROLES) * len(KINDS)} artworks)")


if __name__ == "__main__":
    main()
